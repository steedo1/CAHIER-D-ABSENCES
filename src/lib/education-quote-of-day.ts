/** Stable all day, across reloads and devices; changes at midnight in Abidjan. */
export function educationQuoteOfDay(now = new Date()): string {
  const parts = new Intl.DateTimeFormat("en", { timeZone: "Africa/Abidjan",
    year: "numeric", month: "2-digit", day: "2-digit" }).formatToParts(now);
  const part = (type: string) => Number(parts.find(item => item.type === type)?.value);
  const day = Math.floor(Date.UTC(part("year"), part("month") - 1, part("day")) / 86_400_000);
  return EDUCATION_QUOTES[((day % EDUCATION_QUOTES.length) + EDUCATION_QUOTES.length) % EDUCATION_QUOTES.length];
}
