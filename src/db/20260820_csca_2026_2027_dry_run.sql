official_norm as (
  select o.*,
    upper(regexp_replace(btrim(unaccent(coalesce(o.last_name,'')||' '||coalesce(o.first_name,''))),'\s+',' ','g')) as name_norm
  from official o
),
current_active as (
  select distinct s.id,s.matricule,s.last_name,s.first_name,s.student_person_id,
    upper(regexp_replace(btrim(unaccent(coalesce(s.last_name,'')||' '||coalesce(s.first_name,''))),'\s+',' ','g')) as name_norm
  from public.students s
  join public.class_enrollments ce
    on ce.student_id=s.id
   and ce.institution_id=s.institution_id
   and ce.end_date is null
  join public.classes c on c.id=ce.class_id
  where s.institution_id='ee34ab2a-8033-4e0b-acf0-05979cce1697'::uuid
    and c.academic_year='2026-2027'
),
student_owners as (
  select s.id,s.matricule,s.last_name,s.first_name,s.student_person_id,
    upper(regexp_replace(btrim(unaccent(coalesce(s.last_name,'')||' '||coalesce(s.first_name,''))),'\s+',' ','g')) as name_norm,
    exists(
      select 1 from public.class_enrollments ce
      join public.classes c on c.id=ce.class_id
      where ce.student_id=s.id
        and ce.institution_id=s.institution_id
        and ce.end_date is null
        and c.academic_year='2026-2027'
    ) as active_2026
  from public.students s
  where s.institution_id='ee34ab2a-8033-4e0b-acf0-05979cce1697'::uuid
),
plan as (
  select o.*,
    cm.current_count,
    cm.current_id,
    cm.current_matricule,
    mo.owner_id,
    mo.owner_name_norm,
    mo.owner_active_2026,
    case
      when coalesce(cm.current_count,0)>1 then 'QUARANTINE_AMBIGUOUS_CURRENT_NAME'
      when coalesce(cm.current_count,0)=1
       and regexp_replace(upper(unaccent(coalesce(cm.current_matricule,''))),'[^A-Z0-9]','','g')=o.matricule then 'ALREADY_OK'
      when coalesce(cm.current_count,0)=1
       and nullif(regexp_replace(upper(unaccent(coalesce(cm.current_matricule,''))),'[^A-Z0-9]','','g'),'') is null
       and mo.owner_id is null then 'ASSIGN_FREE_MATRICULE_TO_CURRENT'
      when coalesce(cm.current_count,0)=1
       and nullif(regexp_replace(upper(unaccent(coalesce(cm.current_matricule,''))),'[^A-Z0-9]','','g'),'') is null
       and mo.owner_id is not null
       and mo.owner_id<>cm.current_id
       and mo.owner_active_2026=false
       and mo.owner_name_norm=o.name_norm then 'TRANSFER_HISTORICAL_MATRICULE_TO_CURRENT'
      when coalesce(cm.current_count,0)=1
       and nullif(regexp_replace(upper(unaccent(coalesce(cm.current_matricule,''))),'[^A-Z0-9]','','g'),'') is not null
       and regexp_replace(upper(unaccent(coalesce(cm.current_matricule,''))),'[^A-Z0-9]','','g')<>o.matricule then 'QUARANTINE_CURRENT_HAS_DIFFERENT_MATRICULE'
      when coalesce(cm.current_count,0)=1
       and mo.owner_id is not null
       and mo.owner_name_norm<>o.name_norm then 'QUARANTINE_MATRICULE_OWNER_NAME_MISMATCH'
      when coalesce(cm.current_count,0)=0
       and mo.owner_id is null then 'NEW_STUDENT'
      when coalesce(cm.current_count,0)=0
       and mo.owner_id is not null
       and mo.owner_active_2026=false
       and mo.owner_name_norm=o.name_norm then 'REUSE_HISTORICAL_STUDENT_NO_CURRENT_MATCH'
      when coalesce(cm.current_count,0)=0
       and mo.owner_id is not null
       and mo.owner_name_norm<>o.name_norm then 'QUARANTINE_HISTORICAL_OWNER_NAME_MISMATCH'
      else 'QUARANTINE_OTHER'
    end as action
  from official_norm o
  left join lateral (
    select count(*)::int as current_count,
      min(ca.id::text)::uuid as current_id,
      min(ca.matricule) as current_matricule,
      min(ca.last_name) as last_name,
      min(ca.first_name) as first_name
    from current_active ca
    where ca.name_norm=o.name_norm
  ) cm on true
  left join lateral (
    select min(so.id::text)::uuid as owner_id,
      min(so.name_norm) as owner_name_norm,
      coalesce(bool_or(so.active_2026),false) as owner_active_2026
    from student_owners so
    where regexp_replace(upper(unaccent(coalesce(so.matricule,''))),'[^A-Z0-9]','','g')=o.matricule
  ) mo on true
),
counts as (
  select action,count(*)::int as n from plan group by action
),
refs as (
  select
    count(*) filter(where p.action='TRANSFER_HISTORICAL_MATRICULE_TO_CURRENT')::int as transfer_candidates,
    coalesce(sum((select count(*) from finance.student_charges sc where sc.student_id=p.current_id)) filter(where p.action='TRANSFER_HISTORICAL_MATRICULE_TO_CURRENT'),0)::int as current_charges_preserved,
    coalesce(sum((select count(*) from finance.receipts r where r.student_id=p.current_id)) filter(where p.action='TRANSFER_HISTORICAL_MATRICULE_TO_CURRENT'),0)::int as current_receipts_preserved,
    coalesce(sum((select count(*) from public.attendance_marks a where a.student_id=p.current_id)) filter(where p.action='TRANSFER_HISTORICAL_MATRICULE_TO_CURRENT'),0)::int as current_attendance_rows,
    coalesce(sum((select count(*) from public.student_grades g where g.student_id=p.current_id)) filter(where p.action='TRANSFER_HISTORICAL_MATRICULE_TO_CURRENT'),0)::int as current_grade_rows
  from plan p
)
select
  (select jsonb_object_agg(action,n order by action) from counts) as action_counts,
  (select to_jsonb(refs) from refs) as preservation_checks,
  (
    select jsonb_agg(jsonb_build_object(
      'action',action,
      'matricule',matricule,
      'nom',last_name,
      'prenoms',first_name,
      'source',source_sheet||'!'||source_row
    ) order by action,source_sheet,source_row)
    from plan
    where action like 'QUARANTINE_%'
       or action in ('NEW_STUDENT','REUSE_HISTORICAL_STUDENT_NO_CURRENT_MATCH')
  ) as review_rows;
